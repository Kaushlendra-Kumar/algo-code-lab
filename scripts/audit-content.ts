// Content audit: counts and consistency checks for the curriculum and question bank.
// Writes docs/question-bank-audit.md. Run with `npm run audit:content`.
// C++ correctness is checked separately by scripts/verify-cpp.ts (needs g++).
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { DAYS, EXAMPLES, PATTERNS, PATTERN_BY_ID, QUESTIONS, ZONES } from '../src/content';
import { displayCode, findLine, gapLines } from '../src/content/cpp';
import { TRACES } from '../src/lib/viz/traces';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const issues: string[] = [];
const count = <T,>(xs: T[], key: (x: T) => string) => {
  const m = new Map<string, number>();
  for (const x of xs) m.set(key(x), (m.get(key(x)) ?? 0) + 1);
  return m;
};

// ---------------------------------------------------------------- checks
const ids = count(QUESTIONS, (q) => q.id);
for (const [id, n] of ids) if (n > 1) issues.push(`Duplicate question id ${id}`);
const titles = count(QUESTIONS, (q) => q.title.toLowerCase());
for (const [t, n] of titles) if (n > 1) issues.push(`Duplicate question title "${t}"`);

for (const q of QUESTIONS) {
  const need: [string, unknown][] = [
    ['statement', q.statement],
    ['approach', q.approach],
    ['correctness', q.correctness],
    ['io', q.io],
    ['cpp', q.cpp],
    ['main', q.main],
  ];
  for (const [k, v] of need) if (typeof v !== 'string' || !v.trim()) issues.push(`${q.id}: missing ${k}`);
  if (q.hints.length === 0) issues.push(`${q.id}: no hints`);
  if (q.tests.length < 3) issues.push(`${q.id}: fewer than 3 tests`);
  if (q.examples.length === 0) issues.push(`${q.id}: no statement example`);
  if (q.edgeCases.length === 0) issues.push(`${q.id}: no edge cases`);
  for (const p of q.patterns) if (!PATTERN_BY_ID[p]) issues.push(`${q.id}: unknown pattern ${p}`);
  for (const k of q.keyLines) if (findLine(q.cpp + '\n' + q.main, k.match) === 0) issues.push(`${q.id}: key line not found "${k.match}"`);
}

for (const d of DAYS) {
  const qs = QUESTIONS.filter((q) => q.day === d.day);
  if (qs.length < 5) issues.push(`Day ${d.day}: only ${qs.length} questions`);
  for (const ex of [d.exampleA, d.exampleB]) {
    const shown = displayCode(ex.code);
    for (const k of ex.keyLines) if (findLine(shown, k.match) === 0) issues.push(`${ex.id}: key line not found "${k.match}"`);
    if (ex.bug && ex.code.split(ex.bug.find).length !== 2) issues.push(`${ex.id}: bug.find must occur exactly once`);
    if (ex.trace && !TRACES[ex.trace.id]) issues.push(`${ex.id}: unknown trace ${ex.trace.id}`);
  }
  for (const p of d.patterns) if (!PATTERN_BY_ID[p]) issues.push(`Day ${d.day}: unknown pattern ${p}`);
}

for (const p of PATTERNS) {
  for (const e of p.examples) if (!EXAMPLES[e]) issues.push(`Pattern ${p.id}: example ${e} does not exist`);
  for (const r of p.related ?? []) if (!PATTERN_BY_ID[r]) issues.push(`Pattern ${p.id}: related ${r} does not exist`);
}

// ---------------------------------------------------------------- report
const examples = Object.values(EXAMPLES).map((e) => e.example);
const byDiff = count(QUESTIONS, (q) => q.difficulty);
const byZone = count(QUESTIONS, (q) => q.topic);
const patternUse = count(QUESTIONS.flatMap((q) => q.patterns), (p) => p);
const primaryUse = count(QUESTIONS, (q) => q.patterns[0]);
const unusedPatterns = PATTERNS.filter((p) => !patternUse.has(p.id));

const lines: string[] = [];
lines.push('# Question Bank Audit', '');
lines.push('Generated by `npm run audit:content` from the content files in `src/content`. Do not edit by hand.', '');
lines.push('## Summary', '');
lines.push('| Item | Count |', '| --- | ---: |');
lines.push(`| Curriculum days | ${DAYS.length} |`);
lines.push(`| Questions | ${QUESTIONS.length} |`);
lines.push(`| Stdin/stdout test cases | ${QUESTIONS.reduce((s, q) => s + q.tests.length, 0)} |`);
lines.push(`| Worked C++ examples | ${examples.length} |`);
lines.push(`| Examples with a synced scripted trace | ${examples.filter((e) => e.trace).length} |`);
lines.push(`| Fix-the-bug exercises | ${examples.filter((e) => e.bug).length} |`);
lines.push(`| Fill-the-gap lines | ${examples.reduce((s, e) => s + gapLines(e.code).length, 0)} |`);
lines.push(`| Day quiz questions | ${DAYS.reduce((s, d) => s + d.quiz.length, 0)} |`);
lines.push(`| Patterns | ${PATTERNS.length} |`);
lines.push(`| Zones | ${ZONES.length} |`);
lines.push('');
lines.push('## Consistency checks', '');
if (issues.length === 0) lines.push('No issues found: ids are unique, every question has the required fields, key lines exist in the code, and all pattern / example / trace references resolve.');
else for (const i of issues) lines.push(`- ${i}`);
lines.push('');
lines.push('C++ correctness (compilation with `-Wall -Wextra -Werror`, sanitizers, expected outputs and bug variants) is checked separately by `npm run verify:cpp`, which requires g++.', '');

lines.push('## By difficulty', '', '| Difficulty | Questions |', '| --- | ---: |');
for (const d of ['Easy', 'Medium', 'Hard']) lines.push(`| ${d} | ${byDiff.get(d) ?? 0} |`);
lines.push('');

lines.push('## By zone', '', '| Zone | Days | Questions |', '| --- | --- | ---: |');
for (const z of ZONES) lines.push(`| ${z.name} | ${z.days.join(', ')} | ${byZone.get(z.id) ?? 0} |`);
lines.push('');

lines.push('## By day', '', '| Day | Title | Easy | Medium | Hard | Total |', '| ---: | --- | ---: | ---: | ---: | ---: |');
for (const d of DAYS) {
  const qs = QUESTIONS.filter((q) => q.day === d.day);
  const c = (x: string) => qs.filter((q) => q.difficulty === x).length;
  lines.push(`| ${d.day} | ${d.title} | ${c('Easy')} | ${c('Medium')} | ${c('Hard')} | ${qs.length} |`);
}
lines.push('');

lines.push('## By pattern', '', 'A question can be tagged with several patterns; "primary" counts only its first tag.', '');
lines.push('| Pattern | Family | Tagged | Primary |', '| --- | --- | ---: | ---: |');
for (const p of [...PATTERNS].sort((a, b) => a.family.localeCompare(b.family) || a.name.localeCompare(b.name))) {
  lines.push(`| ${p.name} | ${p.family} | ${patternUse.get(p.id) ?? 0} | ${primaryUse.get(p.id) ?? 0} |`);
}
lines.push('');
if (unusedPatterns.length) {
  lines.push('### Patterns without practice questions', '');
  lines.push('These patterns are taught in the Pattern Library but no question is tagged with them yet:', '');
  for (const p of unusedPatterns) lines.push(`- ${p.name} (\`${p.id}\`)`);
  lines.push('');
}

const out = join(root, 'docs', 'question-bank-audit.md');
mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, lines.join('\n'));
console.log(`Wrote ${out}`);
console.log(`${QUESTIONS.length} questions, ${DAYS.length} days, ${issues.length} issue(s).`);
for (const i of issues) console.log('  - ' + i);
process.exit(issues.length ? 1 : 0);
